import 'dart:io';
import 'package:flutter/services.dart';
import 'package:path_provider/path_provider.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:pdf/pdf.dart';

Future<Uint8List> _loadImageFromAssets(String assetPath) async {
  final ByteData data = await rootBundle.load(assetPath);
  return data.buffer.asUint8List();
}

class PdfBatchGenerator {
  /// Generates a clean class Result Sheet PDF showing all students in one table.
  static Future<File> generateClassResultSheetPdf({
    required List<Map<String, dynamic>> students,
    String filename = 'segak_class_result.pdf',
  }) async {
    final pdf = pw.Document();

    final Uint8List imageData = await _loadImageFromAssets(
      'lib/assets/LOGO.png',
    );
    final pw.MemoryImage image = pw.MemoryImage(imageData);

    // Define table headers
    final headers = [
      'No',
      'Name',
      'Height (cm)',
      'Weight (kg)',
      'BMI',
      'Push Up',
      'Sit Up',
      'Step Test',
      'Sit & Reach',
      'Overall',
    ];

    // Define table data rows
    final data = <List<String>>[];
    for (int i = 0; i < students.length; i++) {
      final s = students[i];
      final segak = Map<String, dynamic>.from(s['segak'] ?? {});
      // Calculate BMI if height and weight are available
      final height = s['height'];
      final weight = s['weight'];
      String bmi = '';
      if (height != null && weight != null && height > 0) {
        final bmiValue = weight / ((height / 100) * (height / 100));
        bmi = bmiValue.toStringAsFixed(2);
      }

      data.add([
        '${i + 1}',
        '${s['username'] ?? ''}',
        '${height ?? ''}',
        '${weight ?? ''}',
        bmi,
        '${segak['Push up'] ?? ''}',
        '${segak['Sit up'] ?? ''}',
        '${segak['Step test'] ?? ''}',
        '${segak['Sit and Reach'] ?? ''}',
        '${segak['Overall'] ?? ''}',
      ]);
    }

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: pw.EdgeInsets.all(24),
        build: (context) => [
          pw.Center(
            child: pw.Column(
              children: [
                pw.Image(image, width: 100, height: 100),
                pw.Text(
                  'Class SEGAK Result Sheet',
                  style: pw.TextStyle(
                    fontSize: 22,
                    fontWeight: pw.FontWeight.bold,
                    color: PdfColors.green,
                  ),
                ),
              ],
            ),
          ),
          pw.SizedBox(height: 12),
          pw.Divider(color: PdfColors.green, thickness: 2),
          pw.SizedBox(height: 16),

          // Table
          pw.Table.fromTextArray(
            border: pw.TableBorder.all(color: PdfColors.green, width: 1),
            headerDecoration: pw.BoxDecoration(color: PdfColors.green),
            headerHeight: 28,
            cellHeight: 26,
            headerStyle: pw.TextStyle(
              fontSize: 8,
              color: PdfColors.white,
              fontWeight: pw.FontWeight.bold,
            ),
            cellStyle: pw.TextStyle(fontSize: 10),
            columnWidths: {
              0: const pw.FixedColumnWidth(25),
              1: const pw.FlexColumnWidth(3),
              2: const pw.FlexColumnWidth(2),
              3: const pw.FlexColumnWidth(2),
              4: const pw.FlexColumnWidth(2),
              5: const pw.FlexColumnWidth(2),
              6: const pw.FlexColumnWidth(2),
              7: const pw.FlexColumnWidth(2),
              8: const pw.FlexColumnWidth(2),
              9: const pw.FlexColumnWidth(2.5),
            },
            headers: headers,
            data: data,
            cellDecoration: (index, data, cell) {
              // alternate row background
              if (index % 2 == 0) {
                return pw.BoxDecoration(color: PdfColors.green.shade(0.05));
              }
              return pw.BoxDecoration();
            },
          ),

          pw.SizedBox(height: 20),
          pw.Align(
            alignment: pw.Alignment.centerLeft,
            child: pw.Text(
              'Total Students: ${students.length}',
              style: pw.TextStyle(color: PdfColors.grey700, fontSize: 11),
            ),
          ),
          pw.SizedBox(height: 8),
          pw.Text(
            'Keep up the good work and stay active!',
            style: pw.TextStyle(color: PdfColors.grey600, fontSize: 10),
          ),
          pw.SizedBox(height: 8),
          pw.Text(
            'This PDF file is auto generated by FitVise.',
            style: pw.TextStyle(color: PdfColors.grey400, fontSize: 10),
          ),
        ],
      ),
    );

    final dir = await getApplicationDocumentsDirectory();
    final file = File('${dir.path}/$filename');
    await file.writeAsBytes(await pdf.save());
    return file;
  }
}
